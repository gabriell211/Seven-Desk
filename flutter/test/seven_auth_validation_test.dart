import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_hbb/common/widgets/seven_auth_validation.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';

void main() {
  final token = 'sd_${List.filled(43, 'a').join()}';

  test('requires an activation generated by a signed-in account', () async {
    final client = MockClient((request) async {
      fail('Malformed tokens must never reach the network');
    });
    expect(await sevenDeskHasValidAccount('', client: client), isFalse);
    expect(await sevenDeskHasValidAccount('legacy-token', client: client),
        isFalse);
    expect(await sevenDeskHasValidAccount('sd_invalid', client: client),
        isFalse);
    client.close();
  });

  test('accepts a verified activation returned by the VPS', () async {
    final client = MockClient((request) async {
      expect(request.url.toString(),
          'https://www.sevendesk.tech/api/app-profile');
      expect(request.headers['Authorization'], 'Bearer $token');
      return http.Response('{"name":"Example","image":""}', 200);
    });
    expect(await sevenDeskHasValidAccount(token, client: client), isTrue);
    client.close();
  });

  test('rejects revoked activation and invalid responses', () async {
    final revoked = MockClient((_) async => http.Response('{}', 401));
    final malformed =
        MockClient((_) async => http.Response('{"success":true}', 200));
    expect(await sevenDeskHasValidAccount(token, client: revoked), isFalse);
    expect(await sevenDeskHasValidAccount(token, client: malformed), isFalse);
    revoked.close();
    malformed.close();
  });

  test('fails closed when the VPS cannot be reached', () async {
    final offline = MockClient((_) async => throw Exception('offline'));
    expect(await sevenDeskHasValidAccount(token, client: offline), isFalse);
    offline.close();
  });
}
